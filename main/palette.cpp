uint8_t g_web_r[3][128]{};
uint8_t g_web_g[3][128]{};
uint8_t g_web_b[3][128]{};
uint8_t g_brightness = 255;

static void load_blob_if_present(nvs_handle_t h, const char *key, void *dst, size_t len) {
    size_t actual = len;
    if (nvs_get_blob(h, key, dst, &actual) != ESP_OK || actual != len) {
        std::memset(dst, 0, len);
    }
}

void palette_init() {
    esp_err_t err = nvs_flash_init();
    if (err == ESP_ERR_NVS_NO_FREE_PAGES || err == ESP_ERR_NVS_NEW_VERSION_FOUND) {
        nvs_flash_erase();
        nvs_flash_init();
    }

    nvs_handle_t h;
    if (nvs_open("palettes", NVS_READONLY, &h) != ESP_OK) return;

    const char *keys[3][3] = {
        {"p0r", "p0g", "p0b"},
        {"p1r", "p1g", "p1b"},
        {"p2r", "p2g", "p2b"},
    };

    for (int i = 0; i < 3; ++i) {
        load_blob_if_present(h, keys[i][0], g_web_r[i], 128);
        load_blob_if_present(h, keys[i][1], g_web_g[i], 128);
        load_blob_if_present(h, keys[i][2], g_web_b[i], 128);
    }

    nvs_close(h);
}

void palette_save_web(uint8_t palette, uint8_t component, const uint8_t data[128]) {
    if (palette >= 3 || component >= 3) return;

    uint8_t *dst = component == 0 ? g_web_r[palette] :
                   component == 1 ? g_web_g[palette] :
                                    g_web_b[palette];
    std::memcpy(dst, data, 128);

    static const char *keys[3][3] = {
        {"p0r", "p0g", "p0b"},
        {"p1r", "p1g", "p1b"},
        {"p2r", "p2g", "p2b"},
    };

    nvs_handle_t h;
    if (nvs_open("palettes", NVS_READWRITE, &h) != ESP_OK) return;
    nvs_set_blob(h, keys[palette][component], data, 128);
    nvs_commit(h);
    nvs_close(h);
}

RGB palette_color(uint8_t channel_zero_based, uint8_t velocity) {
    if (channel_zero_based == 0) return {_r[velocity], _g[velocity], _b[velocity]};
    if (channel_zero_based == 1) return {_r2[velocity], _g2[velocity], _b2[velocity]};
    if (channel_zero_based == 2) return {_r3[velocity], _g3[velocity], _b3[velocity]};

    if (channel_zero_based >= 3 && channel_zero_based <= 5) {
        const uint8_t i = channel_zero_based - 3;
        return {g_web_r[i][velocity], g_web_g[i][velocity], g_web_b[i][velocity]};
    }

    return {0, 0, 0};
}
